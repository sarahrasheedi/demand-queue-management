create table if not exists public.demands (
    id bigint generated by default as identity primary key,
    ref_id text,
    title text not null default '',
    department text,
    requester text,
    status text not null default 'New',
    priority text default 'Medium',
    assigned_developer text,
    estimated_days integer default 1,
    due_date date,
    created_at timestamptz not null default now(),
    smax_id text,
    smax_status text,
    priority_answers jsonb,
    priority_score numeric,
    priority_evaluated_at timestamptz
);

alter table public.demands add column if not exists ref_id text;
alter table public.demands add column if not exists title text;
alter table public.demands add column if not exists department text;
alter table public.demands add column if not exists requester text;
alter table public.demands add column if not exists status text default 'New';
alter table public.demands add column if not exists priority text default 'Medium';
alter table public.demands add column if not exists assigned_developer text;
alter table public.demands add column if not exists estimated_days integer default 1;
alter table public.demands add column if not exists due_date date;
alter table public.demands add column if not exists created_at timestamptz default now();
alter table public.demands add column if not exists smax_id text;
alter table public.demands add column if not exists smax_status text;
alter table public.demands add column if not exists priority_answers jsonb;
alter table public.demands add column if not exists priority_score numeric;
alter table public.demands add column if not exists priority_evaluated_at timestamptz;

alter table public.demands drop constraint if exists demands_smax_id_key;
alter table public.demands add constraint demands_smax_id_key unique (smax_id);

create table if not exists public.authorized_developers (
    id bigint generated by default as identity primary key,
    email text not null unique,
    full_name text
);
alter table public.authorized_developers add column if not exists email text;
alter table public.authorized_developers add column if not exists full_name text;
alter table public.authorized_developers add column if not exists role text not null default 'viewer';
alter table public.authorized_developers drop constraint if exists authorized_developers_role_check;
alter table public.authorized_developers add constraint authorized_developers_role_check check (role in ('viewer', 'editor'));

create or replace function public.current_user_role() returns text
language sql stable security definer set search_path = public as $$
    select role from public.authorized_developers
    where lower(email) = lower(auth.jwt() ->> 'email')
    limit 1
$$;

alter table public.demands enable row level security;
alter table public.authorized_developers enable row level security;

drop policy if exists "Anyone can read demands" on public.demands;
drop policy if exists "Signed-in users can read demands" on public.demands;
drop policy if exists "Viewers and editors can read demands" on public.demands;
create policy "Viewers and editors can read demands" on public.demands
    for select to authenticated using (public.current_user_role() in ('viewer', 'editor'));

drop policy if exists "Signed-in users can add demands" on public.demands;
drop policy if exists "Editors can add demands" on public.demands;
create policy "Editors can add demands" on public.demands
    for insert to authenticated with check (public.current_user_role() = 'editor');

drop policy if exists "Signed-in users can edit demands" on public.demands;
drop policy if exists "Editors can edit demands" on public.demands;
create policy "Editors can edit demands" on public.demands
    for update to authenticated using (public.current_user_role() = 'editor') with check (public.current_user_role() = 'editor');

drop policy if exists "Signed-in users can delete demands" on public.demands;
drop policy if exists "Editors can delete demands" on public.demands;
create policy "Editors can delete demands" on public.demands
    for delete to authenticated using (public.current_user_role() = 'editor');

drop policy if exists "Users can read their own developer row" on public.authorized_developers;
create policy "Users can read their own developer row" on public.authorized_developers
    for select to authenticated using (lower(email) = lower(auth.jwt() ->> 'email'));

